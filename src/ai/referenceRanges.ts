export const METRIC_BY_KEY = new Map(METRICS.map((m) => [m.key, m]))

export function normalizeUnit(def: MetricDef, value: number, unit: string): number | null {
  const factor = def.acceptedUnits[unit.trim().toLowerCase()]
  if (factor === undefined) return null
  return value * factor
}

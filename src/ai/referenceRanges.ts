/**
 * Canonical metric catalog: keys, units, unit conversions, general-adult
 * reference ranges, and plausibility bounds.
 *
 * Ranges are GENERAL ADULT guidance for flagging only — the lab's own
 * printed range takes precedence when available, and nothing here is
 * medical advice. Values are always STORED in the canonical unit.
 */

export type RangeDirection = 'both' | 'high_bad' | 'low_bad'

export interface MetricDef {
  key: string
  label: string
  canonicalUnit: string
  /** unit string (lowercased) → multiply by this factor to get canonical. */
  acceptedUnits: Record<string, number>
  low?: number
  high?: number
  direction: RangeDirection
  /** Values outside these bounds are almost certainly extraction errors. */
  plausibleMin: number
  plausibleMax: number
}

